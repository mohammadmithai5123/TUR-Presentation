import { unlink } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.TUR_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel:'chrome', headless:true, args:['--disable-gpu','--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport:{width:1600,height:1000} });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(`${process.cwd()}/index.html`).href + '#6');
  await page.getByRole('button',{name:'Edit Mode',exact:true}).click();
  const total = await page.locator('#editor-slides option').count(); // works for any deck size
  await page.locator('#editor-preview h1').click();
  await page.locator('#editor-text').fill('Editor test heading');
  await page.locator('#editor-preview h1').filter({hasText:'Editor test heading'}).waitFor();
  await page.locator('#editor-add').click();
  if (await page.locator('#editor-slides option').count() !== total + 1) throw new Error('Add slide failed');
  await page.locator('#editor-up').click();
  await page.locator('#editor-duplicate').click();
  if (await page.locator('#editor-slides option').count() !== total + 2) throw new Error('Duplicate failed');
  await page.locator('#editor-undo').click();
  if (await page.locator('#editor-slides option').count() !== total + 1) throw new Error('Undo failed');
  await page.locator('#editor-add-photo').click();
  await page.locator('#editor-preview > .slide > .route-image').click();
  await page.locator('#editor-image').setInputFiles('assets/images/approved/zainab-market.webp');
  await page.getByText('Image replaced. Saving…',{exact:true}).waitFor();
  await page.locator('#editor-image-size').fill('90');
  await page.locator('#editor-fit').selectOption('contain');
  await page.locator('#editor-preview h1').click();
  await page.locator('#editor-text').fill('Portable $& photo slide');
  await page.locator('#editor-font').fill('3.2');
  await page.locator('#editor-notes').fill('Saved speaker notes');
  await Promise.all([page.waitForNavigation(),page.locator('#editor-save').click()]);
  await page.locator('#edit-mode').waitFor();
  if (await page.locator('#deck > .slide').count() !== total + 1) throw new Error('Save failed');
  if (await page.locator('#deck > .slide.active h1').textContent() !== 'Portable $& photo slide') throw new Error('Text save failed');
  if (!(await page.locator('#deck > .slide.active > .route-image').getAttribute('src')).startsWith('data:image/webp;')) throw new Error('Image save failed');
  await page.getByRole('button',{name:'Edit Mode',exact:true}).click();
  await page.screenshot({path:'editor-preview.png'});
  const downloadPromise = page.waitForEvent('download',{timeout:60000});
  await page.locator('#editor-export').click();
  const download = await downloadPromise;
  await download.saveAs('editor-export-check.html');
  await page.goto(pathToFileURL(`${process.cwd()}/editor-export-check.html`).href);
  console.log('Export browser errors:', errors);
  console.log('Export scripts:', await page.locator('script').count(), 'edit buttons:', await page.locator('#edit-mode').count());
  await page.getByRole('button',{name:'Edit Mode',exact:true}).click();
  if (await page.locator('#editor-slides option').count() !== total + 1) throw new Error('Export lost slides');
  if (!(await page.locator('#editor-slides').textContent()).includes('Portable $& photo slide')) throw new Error('Export changed text');
  await page.locator('#editor-slides').selectOption('13');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#editor-delete').click();
  if (await page.locator('#editor-slides option').count() !== total) throw new Error('Delete failed');
  await page.locator('#editor-undo').click();
  const secondDownload = page.waitForEvent('download',{timeout:60000});
  await page.locator('#editor-export').click();
  await (await secondDownload).saveAs('editor-reexport-check.html');
  await page.goto(pathToFileURL(`${process.cwd()}/editor-reexport-check.html`).href);
  await page.getByRole('button',{name:'Edit Mode',exact:true}).waitFor();
  const routeIndex = await page.locator('#jump option').filter({hasText:'Jinnah House to Al Nadi'}).getAttribute('value');
  await page.locator('#jump').selectOption(routeIndex);
  await page.locator('#next').click();
  await page.locator('.slide.active .route-view.ready').waitFor();
  await page.locator('.slide.active .route-active-photo').click();
  await page.locator('#image-viewer[open]').waitFor();
  await page.keyboard.press('Escape');
  if (await page.locator('#image-viewer').evaluate(node => node.open)) throw new Error('Image viewer did not close');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('PASS: text/font, image upload/size, add, reorder, duplicate, delete, undo, save/reload, portable export/re-export, route expansion and image viewer; no browser errors.');
} finally {
  await browser.close();
  for (const file of ['editor-export-check.html','editor-reexport-check.html','editor-preview.png']) await unlink(file).catch(() => {});
}
